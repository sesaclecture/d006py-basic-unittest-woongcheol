def evn(num1):
    if num1 % 2 == 0:
        return True
    else:
        return False

def avg(num1, num2):
    return (num1 + num2) / 2

def max(num1, num2):
    if num1 > num2:
        return num1
    else:
        return num2

def min(num1, num2):
    if num1 < num2:
        return num1
    else:
        return num2